#!/usr/bin/env python3
"""Convert a PNG into an RGB565 + 1-bit mask C header for the ST7735 display.

The background is removed by flood-filling near-white pixels from the image
border, so white areas inside the artwork (shoes, highlights) survive. The
result is cropped to the artwork, padded to the target aspect ratio, resized
and emitted as `mascot_rgb565` / `mascot_mask`.
"""
import argparse
from collections import deque
from pathlib import Path

from PIL import Image


def background_mask(img, tolerance):
    """Return a bytearray of 1 = background, using a border flood fill."""
    w, h = img.size
    px = img.load()
    seen = bytearray(w * h)
    queue = deque()
    limit = 255 - tolerance

    def is_bg(x, y):
        r, g, b = px[x, y][:3]
        return r >= limit and g >= limit and b >= limit

    for x in range(w):
        for y in (0, h - 1):
            if is_bg(x, y) and not seen[y * w + x]:
                seen[y * w + x] = 1
                queue.append((x, y))
    for y in range(h):
        for x in (0, w - 1):
            if is_bg(x, y) and not seen[y * w + x]:
                seen[y * w + x] = 1
                queue.append((x, y))

    while queue:
        x, y = queue.popleft()
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
            if 0 <= nx < w and 0 <= ny < h:
                idx = ny * w + nx
                if not seen[idx] and is_bg(nx, ny):
                    seen[idx] = 1
                    queue.append((nx, ny))
    return seen


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('input', type=Path)
    ap.add_argument('output', type=Path)
    ap.add_argument('--width', type=int, default=80)
    ap.add_argument('--height', type=int, default=80)
    ap.add_argument('--tolerance', type=int, default=12,
                    help='how close to white still counts as background')
    ap.add_argument('--crop', action='store_true',
                    help='crop to the artwork before resizing')
    ap.add_argument('--padding', type=int, default=0,
                    help='extra margin in source pixels around the artwork')
    args = ap.parse_args()

    img = Image.open(args.input).convert('RGBA')
    white = Image.new('RGBA', img.size, (255, 255, 255, 255))
    img = Image.alpha_composite(white, img)
    bg = background_mask(img, args.tolerance)

    w, h = img.size
    if args.crop:
        minx, miny, maxx, maxy = w, h, -1, -1
        for y in range(h):
            row = y * w
            for x in range(w):
                if not bg[row + x]:
                    if x < minx: minx = x
                    if x > maxx: maxx = x
                    if y < miny: miny = y
                    if y > maxy: maxy = y
        if maxx < 0:
            raise SystemExit('image is entirely background')
        pad = args.padding
        minx = max(0, minx - pad); miny = max(0, miny - pad)
        maxx = min(w - 1, maxx + pad); maxy = min(h - 1, maxy + pad)
        img = img.crop((minx, miny, maxx + 1, maxy + 1))
        cw = maxx - minx + 1
        bg_crop = bytearray()
        for y in range(miny, maxy + 1):
            bg_crop += bg[y * w + minx:y * w + minx + cw]
        bg = bg_crop

    tw, th = args.width, args.height
    w, h = img.size
    scale = min(tw / w, th / h)
    nw, nh = max(1, round(w * scale)), max(1, round(h * scale))
    img = img.resize((nw, nh), Image.LANCZOS)
    mask_img = Image.frombytes('L', (w, h), bytes(255 if b else 0 for b in bg))
    mask_img = mask_img.resize((nw, nh), Image.NEAREST)

    # Place on the target canvas (transparent where the artwork is absent).
    canvas = Image.new('RGBA', (tw, th), (255, 255, 255, 255))
    mask_canvas = Image.new('L', (tw, th), 0)  # 255 = keep
    ox, oy = (tw - nw) // 2, (th - nh) // 2
    canvas.paste(img, (ox, oy))
    # mask semantics: 255 keeps, 0 drops
    keep = Image.eval(mask_img, lambda v: 0 if v else 255)
    mask_canvas.paste(keep, (ox, oy))

    px = canvas.load()
    keep_px = mask_canvas.load()
    rgb = []
    mask = bytearray((tw * th + 7) // 8)
    for y in range(th):
        for x in range(tw):
            r, g, b, _ = px[x, y]
            if keep_px[x, y]:
                rgb.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
                idx = y * tw + x
                mask[idx >> 3] |= 0x80 >> (idx & 7)
            else:
                rgb.append(0x0000)

    name = args.output.stem.replace('-', '_')
    lines = [
        '/* Generated by tools/make-lcd-image.py from %s. Do not edit. */' % args.input.name,
        '#ifndef %s_H' % name.upper(),
        '#define %s_H' % name.upper(),
        '',
        '#include <stdint.h>',
        '',
        '#define MASCOT_W %d' % tw,
        '#define MASCOT_H %d' % th,
        '',
        'static const uint16_t mascot_rgb565[%d] = {' % len(rgb),
    ]
    for i in range(0, len(rgb), 12):
        lines.append('    ' + ', '.join('0x%04x' % v for v in rgb[i:i + 12]) + ',')
    lines.append('};')
    lines.append('')
    lines.append('static const uint8_t mascot_mask[%d] = {' % len(mask))
    for i in range(0, len(mask), 20):
        lines.append('    ' + ', '.join('0x%02x' % v for v in mask[i:i + 20]) + ',')
    lines.append('};')
    lines.append('')
    lines.append('#endif')
    args.output.write_text('\n'.join(lines) + '\n')

    # Preview for eyeballing before flashing.
    preview = Image.new('RGB', (tw, th), (10, 12, 24))
    pp = preview.load()
    for y in range(th):
        for x in range(tw):
            idx = y * tw + x
            if mask[idx >> 3] & (0x80 >> (idx & 7)):
                r5 = (rgb[idx] >> 11) & 0x1F
                g6 = (rgb[idx] >> 5) & 0x3F
                b5 = rgb[idx] & 0x1F
                pp[x, y] = (r5 << 3 | r5 >> 2, g6 << 2 | g6 >> 4, b5 << 3 | b5 >> 2)
    preview.resize((tw * 4, th * 4), Image.NEAREST).save(args.output.with_suffix('.preview.png'))
    kept = sum(bin(v).count('1') for v in mask)
    print('wrote %s (%dx%d, %d visible pixels)' % (args.output, tw, th, kept))


if __name__ == '__main__':
    main()
